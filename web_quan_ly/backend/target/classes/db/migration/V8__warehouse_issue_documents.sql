CREATE TABLE warehouse_issue_documents (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    trip_id BIGINT NULL UNIQUE,
    issue_number VARCHAR(50) NOT NULL UNIQUE,
    issue_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    document_version INT NOT NULL DEFAULT 1,
    company_name VARCHAR(200),
    company_address VARCHAR(255),
    issue_reason VARCHAR(500),
    warehouse_name VARCHAR(150) NOT NULL,
    warehouse_location VARCHAR(150),
    project_name VARCHAR(200) NOT NULL,
    work_item VARCHAR(200),
    recipient_name VARCHAR(150) NOT NULL,
    recipient_phone VARCHAR(20),
    delivery_address VARCHAR(255),
    prepared_by_user_id BIGINT NULL,
    prepared_by_name VARCHAR(150),
    delivery_person_name VARCHAR(150),
    driver_id BIGINT NULL,
    vehicle_id BIGINT NULL,
    quantity_in_words VARCHAR(500),
    notes VARCHAR(1000),
    issued_at DATETIME(6),
    completed_at DATETIME(6),
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_warehouse_issue_trip FOREIGN KEY (trip_id) REFERENCES trips(id),
    CONSTRAINT fk_warehouse_issue_prepared_by FOREIGN KEY (prepared_by_user_id) REFERENCES users(id),
    CONSTRAINT fk_warehouse_issue_driver FOREIGN KEY (driver_id) REFERENCES drivers(id),
    CONSTRAINT fk_warehouse_issue_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id),
    INDEX idx_warehouse_issue_status_date (status, issue_date),
    INDEX idx_warehouse_issue_driver (driver_id),
    INDEX idx_warehouse_issue_vehicle (vehicle_id)
);

CREATE TABLE warehouse_issue_items (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    document_id BIGINT NOT NULL,
    line_number INT NOT NULL,
    item_code VARCHAR(80),
    description VARCHAR(255) NOT NULL,
    specification VARCHAR(255),
    unit VARCHAR(40) NOT NULL,
    requested_quantity DECIMAL(14,3),
    issued_quantity DECIMAL(14,3) NOT NULL,
    returned_quantity DECIMAL(14,3) NOT NULL DEFAULT 0,
    delivered_quantity DECIMAL(14,3),
    condition_note VARCHAR(500),
    confirmation_note VARCHAR(500),
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_warehouse_issue_item_document FOREIGN KEY (document_id) REFERENCES warehouse_issue_documents(id),
    UNIQUE KEY uk_warehouse_issue_line (document_id, line_number)
);

CREATE TABLE warehouse_issue_confirmations (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    document_id BIGINT NOT NULL,
    role_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    signer_name VARCHAR(150) NOT NULL,
    signer_phone VARCHAR(20),
    signed_at DATETIME(6),
    lat DOUBLE,
    lng DOUBLE,
    evidence_url VARCHAR(500),
    note VARCHAR(500),
    created_by_user_id BIGINT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_warehouse_confirmation_document FOREIGN KEY (document_id) REFERENCES warehouse_issue_documents(id),
    CONSTRAINT fk_warehouse_confirmation_user FOREIGN KEY (created_by_user_id) REFERENCES users(id),
    INDEX idx_warehouse_confirmation_document_role (document_id, role_type)
);

CREATE TABLE warehouse_issue_audit_logs (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    document_id BIGINT NOT NULL,
    action VARCHAR(50) NOT NULL,
    from_status VARCHAR(30),
    to_status VARCHAR(30),
    actor_user_id BIGINT NULL,
    actor_name VARCHAR(150),
    note VARCHAR(500),
    created_at DATETIME(6) NOT NULL,
    CONSTRAINT fk_warehouse_audit_document FOREIGN KEY (document_id) REFERENCES warehouse_issue_documents(id),
    CONSTRAINT fk_warehouse_audit_user FOREIGN KEY (actor_user_id) REFERENCES users(id),
    INDEX idx_warehouse_audit_document_created (document_id, created_at)
);
