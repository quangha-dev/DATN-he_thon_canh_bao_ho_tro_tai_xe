CREATE TABLE sync_batches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_uuid varchar(100) NOT NULL UNIQUE,
    user_id bigint NOT NULL REFERENCES users(id),
    device_id bigint REFERENCES mobile_devices(id),
    item_count integer NOT NULL DEFAULT 0 CHECK (item_count >= 0),
    accepted_count integer NOT NULL DEFAULT 0 CHECK (accepted_count >= 0),
    duplicate_count integer NOT NULL DEFAULT 0 CHECK (duplicate_count >= 0),
    rejected_count integer NOT NULL DEFAULT 0 CHECK (rejected_count >= 0),
    status varchar(30) NOT NULL,
    error_summary varchar(1000),
    received_at timestamptz(6) NOT NULL DEFAULT now(),
    completed_at timestamptz(6)
);
CREATE INDEX idx_sync_batches_user_received ON sync_batches (user_id, received_at DESC);

CREATE TABLE sync_batch_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sync_batch_id bigint NOT NULL REFERENCES sync_batches(id) ON DELETE CASCADE,
