-- SafeFleet PostgreSQL 16+ target baseline.
-- This is a clean target schema, not an in-place MySQL migration script.

CREATE SCHEMA IF NOT EXISTS safefleet;
SET search_path TO safefleet, public;

CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

-- ---------------------------------------------------------------------------
-- Identity and access management
-- ---------------------------------------------------------------------------

CREATE TABLE permissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(100) NOT NULL,
    description varchar(255),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX uk_permissions_code_active ON permissions (code) WHERE NOT deleted;

CREATE TABLE roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL,
    description varchar(255),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX uk_roles_name_active ON roles (lower(name)) WHERE NOT deleted;

CREATE TABLE role_permissions (
    role_id bigint NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id bigint NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(80) NOT NULL,
    email varchar(120) NOT NULL,
    password_hash varchar(255) NOT NULL,
    full_name varchar(150) NOT NULL,
    phone varchar(20),
    status varchar(30) NOT NULL,
    role_id bigint NOT NULL REFERENCES roles(id),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX uk_users_username_active ON users (lower(username)) WHERE NOT deleted;
CREATE UNIQUE INDEX uk_users_email_active ON users (lower(email)) WHERE NOT deleted;
CREATE INDEX idx_users_role_status ON users (role_id, status) WHERE NOT deleted;

CREATE TABLE refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash char(64) NOT NULL UNIQUE,
    expires_at timestamptz(6) NOT NULL,
    revoked_at timestamptz(6),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    last_used_at timestamptz(6),
    CONSTRAINT ck_refresh_token_hash CHECK (token_hash ~ '^[0-9a-fA-F]{64}$')
);
CREATE INDEX idx_refresh_tokens_user_active ON refresh_tokens (user_id, expires_at)
    WHERE revoked_at IS NULL;
CREATE INDEX idx_refresh_tokens_expires ON refresh_tokens (expires_at);

-- ---------------------------------------------------------------------------
-- Fleet and assignment history
-- ---------------------------------------------------------------------------

CREATE TABLE drivers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint UNIQUE REFERENCES users(id),
    full_name varchar(150) NOT NULL,
    phone varchar(20) NOT NULL,
    email varchar(120),
    address varchar(255),
    license_number varchar(50) NOT NULL,
    license_class varchar(20) NOT NULL,
    license_expired_at date NOT NULL,
    status varchar(30) NOT NULL,
    safety_score integer NOT NULL DEFAULT 100 CHECK (safety_score BETWEEN 0 AND 100),
    driving_time_today_minutes integer NOT NULL DEFAULT 0 CHECK (driving_time_today_minutes >= 0),
    continuous_driving_minutes integer NOT NULL DEFAULT 0 CHECK (continuous_driving_minutes >= 0),
    total_trips integer NOT NULL DEFAULT 0 CHECK (total_trips >= 0),
    total_alerts integer NOT NULL DEFAULT 0 CHECK (total_alerts >= 0),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX uk_drivers_license_active ON drivers (upper(license_number)) WHERE NOT deleted;
CREATE INDEX idx_drivers_status ON drivers (status) WHERE NOT deleted;

CREATE TABLE vehicles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number varchar(30) NOT NULL,
    vehicle_type varchar(30) NOT NULL,
    brand varchar(80),
    model varchar(80),
    manufacture_year integer CHECK (manufacture_year BETWEEN 1900 AND 2200),
    load_capacity numeric(10,2) CHECK (load_capacity IS NULL OR load_capacity >= 0),
    seat_count integer CHECK (seat_count IS NULL OR seat_count >= 0),
    fuel_type varchar(30),
    status varchar(30) NOT NULL,
    inspection_expired_at date,
    insurance_expired_at date,
    last_lat double precision CHECK (last_lat IS NULL OR last_lat BETWEEN -90 AND 90),
    last_lng double precision CHECK (last_lng IS NULL OR last_lng BETWEEN -180 AND 180),
    last_speed double precision CHECK (last_speed IS NULL OR last_speed >= 0),
    last_updated_at timestamptz(6),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX uk_vehicles_plate_active ON vehicles (upper(regexp_replace(plate_number, '[^A-Za-z0-9]', '', 'g')))
    WHERE NOT deleted;
CREATE INDEX idx_vehicles_type_status ON vehicles (vehicle_type, status) WHERE NOT deleted;

CREATE TABLE devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code varchar(50) NOT NULL,
    name varchar(120) NOT NULL,
    type varchar(40) NOT NULL,
    status varchar(30) NOT NULL,
    phone varchar(20),
    serial_number varchar(80),
    firmware_version varchar(40),
    last_seen_at timestamptz(6),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX uk_devices_code_active ON devices (device_code) WHERE NOT deleted;
CREATE INDEX idx_devices_type_status ON devices (type, status) WHERE NOT deleted;

CREATE TABLE driver_vehicle_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id bigint NOT NULL REFERENCES drivers(id),
    vehicle_id bigint NOT NULL REFERENCES vehicles(id),
    assigned_by_user_id bigint REFERENCES users(id),
    assigned_at timestamptz(6) NOT NULL DEFAULT now(),
    ended_at timestamptz(6),
    reason varchar(255),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    CONSTRAINT ck_driver_vehicle_assignment_time CHECK (ended_at IS NULL OR ended_at >= assigned_at)
);
CREATE UNIQUE INDEX uk_active_assignment_driver ON driver_vehicle_assignments (driver_id) WHERE ended_at IS NULL;
CREATE UNIQUE INDEX uk_active_assignment_vehicle ON driver_vehicle_assignments (vehicle_id) WHERE ended_at IS NULL;
CREATE INDEX idx_assignment_vehicle_history ON driver_vehicle_assignments (vehicle_id, assigned_at DESC);

CREATE TABLE vehicle_device_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id bigint NOT NULL REFERENCES vehicles(id),
    device_id bigint NOT NULL REFERENCES devices(id),
    device_role varchar(30) NOT NULL,
    assigned_at timestamptz(6) NOT NULL DEFAULT now(),
    ended_at timestamptz(6),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    CONSTRAINT ck_vehicle_device_assignment_time CHECK (ended_at IS NULL OR ended_at >= assigned_at)
);
CREATE UNIQUE INDEX uk_active_vehicle_device_role ON vehicle_device_assignments (vehicle_id, device_role)
    WHERE ended_at IS NULL;
CREATE UNIQUE INDEX uk_active_device_assignment ON vehicle_device_assignments (device_id)
    WHERE ended_at IS NULL;

CREATE TABLE device_connection_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id bigint NOT NULL REFERENCES devices(id),
    status varchar(30) NOT NULL,
    lat double precision CHECK (lat IS NULL OR lat BETWEEN -90 AND 90),
    lng double precision CHECK (lng IS NULL OR lng BETWEEN -180 AND 180),
    note varchar(255),
    created_at timestamptz(6) NOT NULL DEFAULT now()
);
CREATE INDEX idx_device_logs_device_created ON device_connection_logs (device_id, created_at DESC);

-- Catalog for bytes stored in MinIO/S3. Do not store the file body here.
CREATE TABLE object_assets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id bigint REFERENCES users(id),
    storage_provider varchar(20) NOT NULL DEFAULT 'MINIO',
    bucket_name varchar(100) NOT NULL,
    object_key varchar(500) NOT NULL,
    original_filename varchar(255),
    content_type varchar(120) NOT NULL,
    size_bytes bigint NOT NULL CHECK (size_bytes >= 0),
    sha256 char(64) NOT NULL,
    encryption_key_ref varchar(255),
    retention_until timestamptz(6),
    status varchar(30) NOT NULL DEFAULT 'AVAILABLE',
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    deleted_at timestamptz(6),
    CONSTRAINT ck_object_asset_sha256 CHECK (sha256 ~ '^[0-9a-fA-F]{64}$'),
    UNIQUE (bucket_name, object_key)
);
CREATE INDEX idx_object_assets_sha256 ON object_assets (sha256);
CREATE INDEX idx_object_assets_owner_created ON object_assets (owner_user_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Trips and operational workflow
-- ---------------------------------------------------------------------------

CREATE TABLE trips (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_code varchar(50) NOT NULL UNIQUE,
    vehicle_id bigint REFERENCES vehicles(id),
    driver_id bigint REFERENCES drivers(id),
    start_location varchar(255) NOT NULL,
    start_lat double precision CHECK (start_lat IS NULL OR start_lat BETWEEN -90 AND 90),
    start_lng double precision CHECK (start_lng IS NULL OR start_lng BETWEEN -180 AND 180),
    end_location varchar(255) NOT NULL,
    end_lat double precision CHECK (end_lat IS NULL OR end_lat BETWEEN -90 AND 90),
    end_lng double precision CHECK (end_lng IS NULL OR end_lng BETWEEN -180 AND 180),
    waypoints_json jsonb,
    planned_route_json jsonb,
    actual_route_json jsonb,
    planned_start_time timestamptz(6),
    actual_start_time timestamptz(6),
    estimated_end_time timestamptz(6),
    actual_end_time timestamptz(6),
    status varchar(30) NOT NULL,
    progress integer NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
    risk_level varchar(30) NOT NULL,
    cancel_reason varchar(255),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false
);
CREATE INDEX idx_trips_driver_status_time ON trips (driver_id, status, planned_start_time) WHERE NOT deleted;
CREATE INDEX idx_trips_vehicle_status_time ON trips (vehicle_id, status, planned_start_time) WHERE NOT deleted;
CREATE INDEX idx_trips_planned_route_gin ON trips USING gin (planned_route_json jsonb_path_ops)
    WHERE planned_route_json IS NOT NULL;

CREATE TABLE trip_timelines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id bigint NOT NULL REFERENCES trips(id),
    action varchar(80) NOT NULL,
    actor_id bigint REFERENCES users(id),
    note varchar(500),
    created_at timestamptz(6) NOT NULL DEFAULT now()
);
CREATE INDEX idx_trip_timelines_trip_created ON trip_timelines (trip_id, created_at);

CREATE TABLE driving_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id bigint NOT NULL REFERENCES drivers(id),
    vehicle_id bigint REFERENCES vehicles(id),
    trip_id bigint REFERENCES trips(id),
    status varchar(30) NOT NULL,
    started_at timestamptz(6) NOT NULL,
    paused_at timestamptz(6),
    resumed_at timestamptz(6),
    ended_at timestamptz(6),
    continuous_minutes integer NOT NULL DEFAULT 0 CHECK (continuous_minutes >= 0),
    total_minutes integer NOT NULL DEFAULT 0 CHECK (total_minutes >= 0),
    over_driving_alert_created boolean NOT NULL DEFAULT false,
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false,
    CONSTRAINT ck_driving_session_time CHECK (ended_at IS NULL OR ended_at >= started_at)
);
CREATE INDEX idx_driving_sessions_driver_status ON driving_sessions (driver_id, status) WHERE NOT deleted;

CREATE TABLE driver_work_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id bigint NOT NULL REFERENCES drivers(id),
    trip_id bigint REFERENCES trips(id),
    work_date date NOT NULL,
    driving_minutes integer NOT NULL DEFAULT 0 CHECK (driving_minutes >= 0),
    rest_minutes integer NOT NULL DEFAULT 0 CHECK (rest_minutes >= 0),
    note varchar(500),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false
);
CREATE INDEX idx_driver_work_logs_driver_date ON driver_work_logs (driver_id, work_date DESC) WHERE NOT deleted;

CREATE TABLE pre_trip_checklists (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id bigint NOT NULL REFERENCES trips(id),
    driver_id bigint NOT NULL REFERENCES drivers(id),
    vehicle_id bigint REFERENCES vehicles(id),
    exterior_checked boolean NOT NULL DEFAULT false,
    tires_checked boolean NOT NULL DEFAULT false,
    brake_checked boolean NOT NULL DEFAULT false,
    lights_checked boolean NOT NULL DEFAULT false,
    camera_checked boolean NOT NULL DEFAULT false,
    gps_checked boolean NOT NULL DEFAULT false,
    documents_checked boolean NOT NULL DEFAULT false,
    checklist_json jsonb,
    note varchar(500),
    created_at timestamptz(6) NOT NULL DEFAULT now(),
    updated_at timestamptz(6),
    deleted boolean NOT NULL DEFAULT false
);
CREATE INDEX idx_pre_trip_trip_driver ON pre_trip_checklists (trip_id, driver_id) WHERE NOT deleted;

